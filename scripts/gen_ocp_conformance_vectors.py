from __future__ import annotations

import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "conformance_vectors" / "ocp_element_codes.txt"

# name: (exp_bits, mantissa_bits, bias, special-value rule)
MINIFLOATS = {
    "E2M1": (2, 1, 1, "finite"),
    "E2M3": (2, 3, 1, "finite"),
    "E3M2": (3, 2, 3, "finite"),
    "E4M3": (4, 3, 7, "e4m3"),
    "E5M2": (5, 2, 15, "ieee"),
}


def decode_minifloat(code: int, e_bits: int, m_bits: int, bias: int, rule: str) -> float:
    sign = -1.0 if (code >> (e_bits + m_bits)) & 1 else 1.0
    e = (code >> m_bits) & ((1 << e_bits) - 1)
    m = code & ((1 << m_bits) - 1)
    e_top = (1 << e_bits) - 1

    if rule == "e4m3" and e == e_top and m == (1 << m_bits) - 1:
        return math.nan
    if rule == "ieee" and e == e_top:
        return sign * math.inf if m == 0 else math.nan

    if e == 0:
        return sign * 2.0 ** (1 - bias) * (m / 2**m_bits)
    return sign * 2.0 ** (e - bias) * (1 + m / 2**m_bits)


def decode_e8m0(code: int) -> float:
    return math.nan if code == 0xFF else 2.0 ** (code - 127)


def fmt_value(v: float) -> str:
    if math.isnan(v):
        return "nan"
    if math.isinf(v):
        return "inf" if v > 0 else "-inf"
    return v.hex()


def main() -> None:
    lines = [
        "# OCP MX v1.0 / OFP8 v1.0 code tables, generated by",
        "# scripts/gen_ocp_conformance_vectors.py -- do not edit by hand.",
        "# <format> <code hex> <value as float.hex, or nan/inf/-inf>",
    ]
    for name, (e_bits, m_bits, bias, rule) in MINIFLOATS.items():
        n_bits = 1 + e_bits + m_bits
        for code in range(1 << n_bits):
            v = decode_minifloat(code, e_bits, m_bits, bias, rule)
            lines.append(f"{name} 0x{code:02X} {fmt_value(v)}")
    for code in range(256):
        lines.append(f"E8M0 0x{code:02X} {fmt_value(decode_e8m0(code))}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(lines) - 3} codes to {OUT}")


if __name__ == "__main__":
    main()
